#pragma once

#include <cstdint>

namespace cg::domain
{
	// 效果类型
	enum class EffectKind : std::uint8_t
	{
		// ========================================
		// 怪兽效果
		// ========================================

		// 启动效果: 主要阶段主动宣言发动,速度1,进入连锁
		IGNITION,

		// 诱发效果: 满足特定条件时触发,速度1,进入连锁
		TRIGGER,

		// 诱发即时效果: 速度2,可在对方回合发动,进入连锁
		QUICK,

		// 永续效果: 表侧表示存在时持续适用,不进入连锁,无发动时点
		CONTINUOUS,

		// ========================================
		// 魔法/陷阱的发动类型
		// ========================================

		// 通常魔法/仪式魔法/永续魔法/装备魔法/场地魔法: 速度1,仅主要阶段发动
		SPELL_ACTIVATE,

		// 速攻魔法/通常陷阱/永续陷阱: 速度2,任意时点响应
		TRAP_QUICK,

		// 反击陷阱: 速度3,仅可被同速连锁
		COUNTER_TRAP,
	};

	// 咒文速度
	enum class EffectSpeed : std::uint8_t
	{
		// 无速度,不入连锁(如STATIC效果)
		NONE = 0,
		// 速度1
		NORMAL = 1,
		// 速度2
		QUICK = 2,
		// 速度3
		COUNTER = 3,
	};

	[[nodiscard]] constexpr auto is_fast_effect(const EffectSpeed speed) noexcept -> bool
	{
		return speed == EffectSpeed::QUICK || speed == EffectSpeed::COUNTER;
	}

	// 限定静态效果适用时卡牌所在区域(只有效果所属卡牌位于指定区域才有效果)
	enum class StaticEffectRegion : std::uint8_t
	{
		// 不限定区域,任何区域都适用
		ALL,
		// 怪兽区域
		MONSTER,
		// 灵摆区域
		PENDULUM,
		// 无所谓什么区域,只要在场上就行
		FIELD,
	};

	// 限定静态效果适用玩家
	enum class StaticEffectTargetRange : std::uint8_t
	{
		// 只波及自己
		SELF,
		// 只波及对手
		OPPONENT,
		// 双方都波及
		ALL,
	};

	// 限定静态效果适用生命周期
	enum class StaticEffectLifetime : std::uint8_t
	{
		// 永久持续(只有效果还适用)
		PERMANENT,
		// 到本回合结束时失效
		END_TURN,
		// 到本阶段结束时失效
		END_PHASE,
		// 未装备时失效
		UNEQUIPPED,
		// 不在场上时失效
		NOT_ON_FIELD,
	};

	// 效果提供的抗性
	enum class Protection : std::uint8_t
	{
		// ==========================================================
		// 破坏抗性
		// ==========================================================

		// 不被效果破坏
		DESTROY,
		// 不被战斗破坏
		BATTLE,

		// ==========================================================
		// 效果抗性
		// ==========================================================

		// 不能成为效果的对象
		TARGET,
		// 不受其他卡效果影响
		IMMUNE_TO_OTHER_EFFECTS,
		// 不受"发动的效果"影响(如念力终结处刑者[60465049])
		// 注意: 永续效果、装备效果等不入连锁的效果仍然适用
		UNAFFECTED_BY_ACTIVATED,
		// 不受任何效果影响(只能战斗/解放处理)
		UNAFFECTED_BY_EFFECTS,

		// ==========================================================
		// 规则性保护(非效果抗性)
		// ==========================================================

		// 不能被解放(召唤僧、五重魔术师)
		CANNOT_BE_RELEASED,
		// 不能作为融合/同调/超量/连接召唤的素材
		CANNOT_BE_MATERIAL,

		// ==========================================================
		// 定向抗性
		// ==========================================================

		// 不受特定属性的效果影响
		UNAFFECTED_BY_ATTRIBUTE,
		// 不受特定种族的效果影响
		UNAFFECTED_BY_RACE,
		// 不受对方控制的效果影响
		UNAFFECTED_BY_OPPONENT,
	};

	// 效果提供的破坏替代
	enum class DestroyReplacement : std::uint8_t
	{
		// 移除一个超量素材代替破坏
		REMOVE_OVERLAY,
		// 墓地除外代替破坏
		BANISH_FROM_GRAVEYARD,
		// 破坏装备卡代替破坏
		DESTROY_EQUIP,
		// 破坏装备卡代替破坏,仅限战斗破坏
		DESTROY_EQUIP_BATTLE_ONLY,
	};

	// 效果产生的限制效果
	//
	// 用于表示"不能执行某个行为"的封锁类效果
	// 与 EffectCategory 的区别:
	// - Restriction 是禁止性规则(不能做X)
	// - EffectCategory 是效果的行为(做X)
	enum class Restriction : std::uint8_t
	{
		// ==========================================================
		// 召唤/特殊召唤限制
		// ==========================================================

		// 不能通常召唤
		NORMAL_SUMMON,
		// 不能反转召唤
		FLIP_SUMMON,
		// 不能特殊召唤
		SPECIAL_SUMMON,
		// 不能盖放(里侧守备表示召唤)
		SET_MONSTER,

		// ==========================================================
		// 效果发动限制
		// ==========================================================

		// 不能发动效果(禁止令[43711255]的"不能作卡的发动以及效果的发动")
		ACTIVATE,
		// 不能触发效果(诱发效果无法发动)
		TRIGGER,
		// 不能适用效果(发动被无效/效果被无效后的状态)
		APPLY,

		// ==========================================================
		// 行为限制
		// ==========================================================

		// 不能抽卡
		DRAW,
		// 不能攻击
		ATTACK,
		// 不能直接攻击
		DIRECT_ATTACK,
		// 不能改变表示形式
		// 注意: 禁止令[43711255]的"不能攻击以及表示形式的变更"不包含效果导致的变更
		POSITION_CHANGE,
		// 不能改变控制权
		CONTROL_CHANGE,
		// 不能盖放魔陷
		SET_SPELL_TRAP,

		// ==========================================================
		// 移动限制
		// ==========================================================

		// 不能在场上出现(禁止令[43711255]的"不能在场上出现")
		APPEAR_ON_FIELD,
		// 不能加入手牌
		TO_HAND,
		// 不能加入墓地(送入墓地的效果不适用)
		TO_GRAVEYARD,
		// 不能除外
		TO_BANISHED,
		// 不能返回卡组
		TO_DECK,

		// ==========================================================
		// 阶段/回合限制
		// ==========================================================

		// 不能进入战斗阶段
		BATTLE_PHASE,
		// 不能进入特定阶段(如跳过抽卡阶段)
		SKIP_PHASE,
		// 不能进行连锁
		CHAIN,
	};

	// 效果类别
	//
	// 描述效果"做了什么"，用于效果分类、搜索、条件判断
	// 分类依据: 效果的主要行为
	enum class EffectCategory : std::uint8_t
	{
		// ==========================================================
		// 抽卡/检索/回收
		// ==========================================================

		// 从卡组抽卡
		DRAW,
		// 从卡组检索加入手牌
		SEARCH,
		// 从墓地回收
		RECOVER_FROM_GRAVEYARD,
		// 从除外区回收
		RECOVER_FROM_BANISHED,

		// ==========================================================
		// 卡片移动(从A到B)
		// ==========================================================

		// 加入手牌
		TO_HAND,
		// 送入墓地
		TO_GRAVEYARD,
		// 除外
		TO_BANISHED,
		// 返回卡组
		TO_DECK,
		// 返回额外卡组
		TO_EXTRA_DECK,
		// 舍弃手牌
		DISCARD,
		// 解放
		RELEASE,
		// 装备
		EQUIP,

		// ==========================================================
		// 破坏/无效
		// ==========================================================

		// 破坏
		DESTROY,
		// 无效发动/无效效果
		NEGATE,
		// 禁用效果(持续无效)
		DISABLE,

		// ==========================================================
		// 战斗相关
		// ==========================================================

		// 改变表示形式
		POSITION_CHANGE,
		// 改变控制权
		CONTROL_CHANGE,
		// 特殊召唤
		SPECIAL_SUMMON,

		// ==========================================================
		// 数值/状态变更
		// ==========================================================

		// 恢复生命值
		RECOVER,
		// 造成伤害
		DAMAGE,
		// 改变攻击力
		MODIFY_ATTACK,
		// 改变守备力
		MODIFY_DEFENSE,

		// ==========================================================
		// 生成/放置
		// ==========================================================

		// 生成衍生物
		TOKEN,
		// 放置指示物
		COUNTER,

		// ==========================================================
		// 其他
		// ==========================================================

		// 宣言(卡名/种族/属性等)
		DECLARE,
		// 揭示未知卡(如三战之才)
		REVEAL,
	};

	// 效果附加属性/标志
	enum class EffectProperty : std::uint8_t
	{
		// ==========================================================
		// 发动时点限定
		// ==========================================================

		// 可以在伤害步骤发动(欧尼斯特[37742478])
		ACTIVATE_IN_DAMAGE_STEP,
		// 可以在伤害计算时发动(星尘龙[44508094])
		ACTIVATE_IN_DAMAGE_CALCULATION,
		// 只能在自己回合发动
		ONLY_DURING_OWN_TURN,
		// 只能在对方回合发动
		ONLY_DURING_OPPONENT_TURN,

		// ==========================================================
		// 发动性质
		// ==========================================================

		// 必发效果(条件满足时必须发动)
		MANDATORY,
		// 任意效果(条件满足时可以选择不发动)
		OPTIONAL,
		// 一回合只能发动一次
		ONCE_PER_TURN,
		// 一回合只能使用一次(包括被无效的发动)
		HARD_ONCE_PER_TURN,

		// ==========================================================
		// 目标相关
		// ==========================================================

		// 以卡牌为对象(死者苏生[83764718])
		TARGET_CARD,
		// 以玩家为对象(冥王结界波[54693926] -- 受到的伤害变为0)
		TARGET_PLAYER,
		// 不取对象(处理时才选择目标)
		NO_TARGET,

		// ==========================================================
		// 处理方式
		// ==========================================================

		// 延时处理(加速同调星尘龙[30983281])
		DELAYED_TRIGGER,
		// 作为超量素材时适用(`拥有这张卡作为素材的怪兽获得以下效果`)
		ACTIVATE_AS_OVERLAY,
		// 仅在效果源所在区域适用(召唤僧[423585] -- `只要这张卡在怪兽区存在,这张卡就不能解放`仅在处于怪兽区有效)
		SOURCE_ZONE_ONLY,

		// ==========================================================
		// 无效/禁用相关
		// ==========================================================

		// 无法被无效(发动/效果不能被无效化)
		CANNOT_BE_NEGATED,
		// 无法被无效(如规则自肃)
		CANNOT_BE_DISABLED,
		// 免疫穿透(禁止令[43711255])
		IGNORE_IMMUNITY,

		// ==========================================================
		// 信息操作
		// ==========================================================

		// 揭示未知卡(三战之才[25311006])
		REVEAL,
	};
}
