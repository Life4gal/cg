#pragma once

#include <cstdint>

namespace cg::domain
{
	// 卡牌移动/状态变化的原因
	//
	// 这张卡为什么离开了原来的位置/改变了状态
	// 分类依据: 触发这一变化的上层来源
	//
	// 同一个变化可能有多个原因,如"因效果破坏"同时是 EFFECT 和 DESTROY
	enum class Reason: std::uint8_t
	{
		// ==========================================================
		// 规则导致
		// ==========================================================

		// 因游戏规则本身导致(如回合结束手牌调整、灵摆区卡送额外卡组)
		RULE,

		// ==========================================================
		// 玩家动作导致
		// ==========================================================

		// 因抽卡动作导致(抽卡阶段抽卡、效果抽卡)
		DRAW,
		// 因舍弃导致(从手牌丢弃,如手牌调整、效果舍弃)
		DISCARD,
		// 因解放导致(作为 cost 解放,如上级召唤解放、效果解放)
		RELEASE,

		// ==========================================================
		// 效果导致
		// ==========================================================

		// 因效果导致(泛称,包含效果破坏、效果除外、效果送墓等)
		EFFECT,
		// 因效果破坏导致(是 EFFECT 的子类,可与 EFFECT 组合使用)
		DESTROY,
		// 因失去对象导致(装备卡装备对象离场、效果对象消失)
		LOST_TARGET,
		// 因作为超量素材被取除导致
		REMOVE_OVERLAY,
		// 因代替破坏导致(如超量素材代替破坏、装备卡代替破坏)
		REPLACE,

		// ==========================================================
		// 战斗导致
		// ==========================================================

		// 因战斗导致(泛称,包含战斗破坏、战斗伤害等)
		BATTLE,
		// 因战斗破坏导致(是 BATTLE 的子类，可与 BATTLE 组合使用)
		BATTLE_DESTROY,

		// ==========================================================
		// 代价导致
		// ==========================================================

		// 因 COST 导致(支付发动费用,如"把这张卡解放才能发动")
		COST,

		// ==========================================================
		// 召唤手续导致
		//
		// 这些是"召唤素材被送去墓地/除外"的原因
		// 它们同时可能属于"玩家动作"或"效果"
		// 单独列出是为了让"因作为融合素材送入墓地"这类条件可以被精确匹配
		// ==========================================================

		// 因召唤手续导致(泛称)
		SUMMON,
		// 因作为仪式素材导致
		RITUAL,
		// 因作为融合素材导致
		FUSION,
		// 因作为同调素材导致
		SYNCHRO,
		// 因作为超量素材导致
		XYZ,
		// 因作为连接素材导致
		LINK,

		// ==========================================================
		// 其他
		// ==========================================================

		// 因卡牌自身效果导致(区别于EFFECT: 特指"这张卡自己的效果")
		// 如"这张卡被自身效果除外"
		SELF_EFFECT,
	};
}
